#!/usr/bin/env node
/**
 * Generate src/lib/police/newzealand.ts from the curated CSV.
 *
 * Source: src/lib/police/data/nz_police_stations.csv
 *   columns: station_name,lat,lon  (one row per station; lat/lon WGS84)
 *
 * Run:  node scripts/generate_nz_police.js
 *
 * Re-run whenever the CSV changes. The emitted file is checked in so the build
 * never depends on this script — this just keeps regeneration deterministic.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSV = path.join(ROOT, 'src/lib/police/data/nz_police_stations.csv');
const OUT = path.join(ROOT, 'src/lib/police/newzealand.ts');

/** Minimal CSV line parser — handles double-quoted fields containing commas. */
function parseLine(line) {
  const out = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') inQuotes = false;
      else cur += ch;
    } else if (ch === '"') inQuotes = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

/** name -> stable slug; strips Māori macrons (ā→a …) so ids are ASCII. */
function slug(name) {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const raw = fs.readFileSync(CSV, 'utf8');
const lines = raw.split(/\r?\n/).filter((l) => l.trim().length > 0);
const header = parseLine(lines[0]).map((h) => h.trim().toLowerCase());
const iName = header.indexOf('station_name');
const iLat = header.indexOf('lat');
const iLon = header.indexOf('lon');
if (iName < 0 || iLat < 0 || iLon < 0) {
  throw new Error(`unexpected CSV header: ${lines[0]}`);
}

const seen = new Map();
const stations = [];
for (let i = 1; i < lines.length; i++) {
  const cols = parseLine(lines[i]);
  const name = cols[iName].trim();
  const lat = Number(cols[iLat]);
  const lng = Number(cols[iLon]);
  if (!name || !Number.isFinite(lat) || !Number.isFinite(lng)) {
    throw new Error(`bad row ${i + 1}: ${lines[i]}`);
  }
  let id = `nz-police-${slug(name)}`;
  // Guard against slug collisions (defensive — names are unique today).
  const n = seen.get(id) || 0;
  seen.set(id, n + 1);
  if (n > 0) id = `${id}-${n + 1}`;
  stations.push({ id, lat, lng, name });
}

const rows = stations
  .map((s) => {
    const name = JSON.stringify(s.name);
    return `  { id: ${JSON.stringify(s.id)}, lat: ${s.lat}, lng: ${s.lng}, name: ${name}, operator: 'New Zealand Police', source: 'NZ Police', osm_url: null },`;
  })
  .join('\n');

const out = `// AUTO-GENERATED by scripts/generate_nz_police.js — do not edit by hand.
// Source: src/lib/police/data/nz_police_stations.csv (${stations.length} stations).
// Re-run \`node scripts/generate_nz_police.js\` after editing the CSV.
import type { BBox } from '@/lib/overpass';
import type { CuratedPoliceDataset, PoliceStation } from './types';

/**
 * Coverage box(es) New Zealand Police data is authoritative for. Live OSM
 * results inside these boxes are dropped in favour of the curated set.
 * Two boxes: the main islands + Stewart Island, and the Chatham Islands
 * (which sit just east of the 180° antimeridian, ~ -176.6°).
 */
export const NZ_COVERAGE: BBox[] = [
  [-47.5, 166.0, -34.0, 178.7], // main + Stewart Island
  [-44.5, -177.2, -43.4, -176.0], // Chatham Islands
];

export const NZ_POLICE_STATIONS: PoliceStation[] = [
${rows}
];

export const NZ_POLICE: CuratedPoliceDataset = {
  id: 'nz',
  country: 'New Zealand',
  coverage: NZ_COVERAGE,
  stations: NZ_POLICE_STATIONS,
};
`;

fs.writeFileSync(OUT, out);
console.log(`wrote ${stations.length} stations -> ${path.relative(ROOT, OUT)}`);
